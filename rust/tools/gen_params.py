#!/usr/bin/env python3
"""Generates plugin/src/params_gen.rs (the nih-plug parameter struct) from dsp/src/params.rs.
Run from rust/:  python3 tools/gen_params.py"""
import re
src = open('dsp/src/params.rs').read()
rows = re.findall(r'ParamDef \{ id: "(\w+)", name: "([^"]+)", lo: (-?[\d.e-]+), hi: (-?[\d.e-]+), def: (-?[\d.e-]+), soft_lo: [^,]+, soft_hi: [^,]+, group: Group::(\w+), page: (\d), flags: ([^}]+?) \}', src)
assert len(rows) == 52, len(rows)
o = ['// @generated by tools/gen_params.py from dsp/src/params.rs - do not edit by hand.',
     'use nih_plug::prelude::*;',
     'use nih_plug_egui::EguiState;',
     'use seedling_dsp::params::{NUM_PARAMS, REVERB_NAMES, SOURCE_NAMES};',
     'use std::sync::atomic::AtomicU32;',
     'use std::sync::{Arc, Mutex};', '',
     '#[derive(Params)]', 'pub struct SeedParams {',
     '    #[persist = "editor-state"] pub editor_state: Arc<EguiState>,',
     '    #[persist = "seed"] pub seed: Arc<AtomicU32>,',
     '    #[persist = "wavetable"] pub wavetable: Arc<Mutex<String>>,',
     '    #[persist = "wavetable-info"] pub wavetable_info: Arc<Mutex<String>>,',
     '    #[persist = "skin"] pub skin: Arc<Mutex<String>>,',
     '    #[id = "chaos"] pub chaos: FloatParam,',
     '    #[id = "auto_tune"] pub auto_tune: BoolParam,']
for r in rows:
    typ = 'BoolParam' if 'SWITCH' in r[7] else ('IntParam' if 'STEP' in r[7] else 'FloatParam')
    o.append(f'    #[id = "{r[0]}"] pub {r[0]}: {typ},')
o += ['}', '', 'impl Default for SeedParams {', '    fn default() -> Self {', '        Self {',
      '            editor_state: EguiState::from_size(1200, 900),',
      '            seed: Arc::new(AtomicU32::new(0)),',
      '            wavetable: Arc::new(Mutex::new(String::new())),',
      '            wavetable_info: Arc::new(Mutex::new(String::new())),',
      '            skin: Arc::new(Mutex::new(String::new())),',
      '            chaos: FloatParam::new("Chaos", 0.0, FloatRange::Linear { min: 0.0, max: 1.0 }).with_value_to_string(formatters::v2s_f32_rounded(2)),',
      '            auto_tune: BoolParam::new("Auto Tune", true),']
for r in rows:
    i, n, lo, hi, d, g, pg, fl = r
    if 'SWITCH' in fl:
        e = f'BoolParam::new("{n}", {"true" if float(d) >= 0.5 else "false"})'
    elif 'STEP' in fl:
        names = 'SOURCE_NAMES' if i == 'src_type' else 'REVERB_NAMES'
        e = (f'IntParam::new("{n}", {int(float(d))}, IntRange::Linear {{ min: {int(float(lo))}, max: {int(float(hi))} }})'
             f'.with_value_to_string(Arc::new(|v| {names}[v.clamp(0, {names}.len() as i32 - 1) as usize].to_string()))')
    else:
        e = (f'FloatParam::new("{n}", {d}, FloatRange::Linear {{ min: {lo}, max: {hi} }})'
             f'.with_value_to_string(formatters::v2s_f32_rounded(2))')
    o.append(f'            {i}: {e},')
o += ['        }', '    }', '}', '', 'impl SeedParams {',
      '    /// The 52 synth values in seed order (real-world units).',
      '    pub fn values(&self) -> [f32; NUM_PARAMS] {', '        [']
for r in rows:
    f = r[0]
    o.append(f'            {"(self.%s.value() as i32 as f32)" % f if "STEP" in r[7] else ("(self.%s.value() as u8 as f32)" % f if "SWITCH" in r[7] else "self.%s.value()" % f)},')
o += ['        ]', '    }', '',
      '    /// Pointers to the 52 synth parameters in seed order (for setting them from the editor).',
      '    pub fn ptrs(&self) -> [ParamPtr; NUM_PARAMS] {', '        [']
for r in rows:
    o.append(f'            self.{r[0]}.as_ptr(),')
o += ['        ]', '    }', '}', '']
open('plugin/src/params_gen.rs', 'w').write('\n'.join(o))
print('ok', len(rows))
